#!/usr/bin/env python3
"""Bundle the DeepX ES modules into one classic script (deepx-bundle.js) for classic AntiGem workers.

Usage: python3 tools/build_classic_bundle.py <output.js>
The bundle defines self.DeepXFlow = { configureDeepX, deepxExecute, deepxGenerate, loginCheck, mcpListener, ... }.
deepx-agent-page.js and page-helpers.js are injected into pages and must be copied next to the bundle.
"""
import os, re, sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ORDER = ["constants", "flow-client", "storyboard-analyzer", "flow-workflows", "deepx-knowledge", "deepx-agent", "deepx-core"]
IMPORT_RE = re.compile(r"^import\s*\{([^}]*)\}\s*from\s*['\"]\./([\w.-]+)\.js['\"];?\s*$", re.M)
EXPORT_DECL = re.compile(r"^export\s+(async\s+function|function|const|let|class)\s+([A-Za-z_$][\w$]*)", re.M)
EXPORT_LIST = re.compile(r"^export\s*\{([^}]*)\};?\s*$", re.M)


def convert(name, src):
    exports = []
    def imp(m):
        names = []
        for part in m.group(1).split(","):
            part = part.strip()
            if not part:
                continue
            if " as " in part:
                a, b = [x.strip() for x in part.split(" as ")]
                names.append(f"{a}: {b}")
            else:
                names.append(part)
        return f"const {{ {', '.join(names)} }} = __m['{m.group(2)}'];"
    src = IMPORT_RE.sub(imp, src)
    if re.search(r"^import\s", src, re.M):
        raise SystemExit(f"{name}: unsupported import form")
    def decl(m):
        exports.append(m.group(2))
        return m.group(1) + " " + m.group(2)
    src = EXPORT_DECL.sub(decl, src)
    def lst(m):
        for part in m.group(1).split(","):
            part = part.strip()
            if not part:
                continue
            if " as " in part:
                a, b = [x.strip() for x in part.split(" as ")]
                exports.append(f"{b}: {a}")
            else:
                exports.append(part)
        return ""
    src = EXPORT_LIST.sub(lst, src)
    if re.search(r"^export\s", src, re.M) or "import(" in src:
        raise SystemExit(f"{name}: unsupported export/dynamic import")
    return f"__m['{name}'] = (function () {{\n'use strict';\n{src}\nreturn {{ {', '.join(exports)} }};\n}})();\n"


def main():
    out = sys.argv[1]
    parts = ["// AUTO-GENERATED by deepx-google-flow/tools/build_classic_bundle.py — do not edit.\n",
             "// DeepX Google Flow engine as a classic script for AntiGem classic workers (importScripts).\n",
             "(function () {\n'use strict';\nconst __m = {};\n"]
    for n in ORDER:
        parts.append(convert(n, open(os.path.join(HERE, n + ".js"), encoding="utf-8").read()))
    parts.append("self.DeepXFlow = Object.assign({}, __m['deepx-core'], { __modules: __m });\n})();\n")
    open(out, "w", encoding="utf-8").write("".join(parts))
    print("wrote", out)


if __name__ == "__main__":
    main()
